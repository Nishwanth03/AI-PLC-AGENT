
from pathlib import Path
import re

from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import FileResponse
from pydantic import BaseModel, Field

app = FastAPI(title="AI PLC Agent")

BASE_DIR = Path(__file__).resolve().parent.parent
OUTPUT_DIR = BASE_DIR / "generated"
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["http://localhost:5173"],
    allow_credentials=False,
    allow_methods=["GET", "POST"],
    allow_headers=["Content-Type"],
)


class LogicRequest(BaseModel):
    requirement: str = Field(min_length=10, max_length=5000)
    block_name: str = "FB_PumpControl"
    block_type: str = "FB"


class LogicResponse(BaseModel):
    status: str
    block_name: str
    requirement: str
    assumptions: list[str]
    scl_code: str
    warnings: list[str]


def generate_mock_scl(request: LogicRequest) -> LogicResponse:
    """
    Initial deterministic prototype.
    This is NOT an AI model and does not interpret arbitrary requirements.
    """

    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]{0,60}",
                        request.block_name):
        raise HTTPException(
            status_code=400,
            detail="Invalid block name."
        )

    if request.block_type != "FB":
        raise HTTPException(
            status_code=400,
            detail="The initial prototype supports FB only."
        )

    text = request.requirement.lower()

    # Only generate this predefined example when the request
    # clearly mentions a pump, start, stop, and overload.
    if not all(word in text for word in
               ("pump", "start", "stop", "overload")):
        return LogicResponse(
            status="needs_clarification",
            block_name=request.block_name,
            requirement=request.requirement,
            assumptions=[],
            scl_code="",
            warnings=[
                "The mock generator supports only a predefined "
                "pump start/stop/overload example.",
                "No PLC code was generated. Add a real AI provider "
                "or implement a dedicated template for this request."
            ]
        )

    code = f"""FUNCTION_BLOCK "{request.block_name}"
{{
    S7_Optimized_Access := 'TRUE'
}}
VERSION : 0.1

VAR_INPUT
    Start_PB       : Bool;
    Stop_PB        : Bool;
    Motor_Overload : Bool;
END_VAR

VAR_OUTPUT
    Pump_Run       : Bool;
    Overload_Alarm : Bool;
END_VAR

BEGIN
    IF #Stop_PB OR #Motor_Overload THEN
        #Pump_Run := FALSE;
    ELSIF #Start_PB THEN
        #Pump_Run := TRUE;
    END_IF;

    #Overload_Alarm := #Motor_Overload;
END_FUNCTION_BLOCK
"""

    return LogicResponse(
        status="draft",
        block_name=request.block_name,
        requirement=request.requirement,
        assumptions=[
            "Start_PB and Stop_PB are Boolean signals.",
            "Motor_Overload is TRUE when an overload is detected.",
            "The block retains Pump_Run between scans when neither "
            "Start_PB nor Stop_PB is active.",
            "This is a non-safety-rated illustrative control example."
        ],
        scl_code=code,
        warnings=[
            "Generated by a deterministic mock template, not an LLM.",
            "Review stop priority, restart behavior, permissives, "
            "and tag mappings before using this logic.",
            "SCL syntax and import compatibility must be verified "
            "in the target TIA Portal version."
        ]
    )


@app.get("/health")
def health():
    return {
        "status": "ok",
        "service": "AI PLC Agent",
        "mode": "mock"
    }


@app.post("/api/generate", response_model=LogicResponse)
def generate_logic(request: LogicRequest):
    return generate_mock_scl(request)


@app.post("/api/export")
def export_scl(request: LogicRequest):
    result = generate_mock_scl(request)

    if result.status != "draft" or not result.scl_code:
        raise HTTPException(
            status_code=422,
            detail=result.warnings
        )

    output_path = OUTPUT_DIR / f"{request.block_name}.scl"
    output_path.write_text(result.scl_code, encoding="utf-8")

    return FileResponse(
        path=output_path,
        filename=f"{request.block_name}.scl",
        media_type="text/plain"
    )
